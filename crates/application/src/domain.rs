use std::{str::FromStr, sync::Arc};

use async_trait::async_trait;

use crate::{ApplicationError, Principal};

macro_rules! domain_commands {
    ($($variant:ident => $name:literal / $scope:literal),+ $(,)?) => {
        /// Closed set of non-Conversation product commands supported by remote hosts.
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        pub enum DomainCommand {
            $($variant,)+
        }

        impl DomainCommand {
            pub const ALL: &'static [Self] = &[$(Self::$variant,)+];

            pub fn capability_scopes() -> Vec<&'static str> {
                let mut scopes = std::collections::BTreeSet::new();
                for command in Self::ALL {
                    scopes.insert(command.required_scope());
                }
                for scope in [
                    "conversation.read",
                    "conversation.write",
                    "conversation.attach",
                    "conversation.permission",
                    "conversation.question",
                    "conversation.cancel",
                    "conversation.steer",
                    "workflow.read",
                    "workflow.write",
                    "workflow.run",
                    "workflow.approve",
                    "device.pair",
                    "device.revoke",
                    "notification.summary",
                    "offline.read",
                    "preview.proxy",
                    "delegation.read",
                ] {
                    scopes.insert(scope);
                }
                scopes.into_iter().collect()
            }

            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $name,)+
                }
            }

            pub const fn required_scope(self) -> &'static str {
                match self {
                    $(Self::$variant => $scope,)+
                }
            }
        }

        impl FromStr for DomainCommand {
            type Err = ();

            fn from_str(value: &str) -> Result<Self, Self::Err> {
                Self::ALL
                    .iter()
                    .copied()
                    .find(|command| command.as_str() == value)
                    .ok_or(())
            }
        }
    };
}


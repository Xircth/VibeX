#[async_trait]
pub trait ApplicationDomainPort: Send + Sync {
    async fn execute(
        &self,
        principal: &Principal,
        command: DomainCommand,
        args: serde_json::Value,
    ) -> Result<serde_json::Value, ApplicationError>;
}

pub(crate) struct UnavailableApplicationDomains;

#[async_trait]
impl ApplicationDomainPort for UnavailableApplicationDomains {
    async fn execute(
        &self,
        _principal: &Principal,
        command: DomainCommand,
        _args: serde_json::Value,
    ) -> Result<serde_json::Value, ApplicationError> {
        Err(ApplicationError::capability_unavailable(format!(
            "{} is not configured",
            command.as_str()
        )))
    }
}

pub(crate) fn unavailable_domains() -> Arc<dyn ApplicationDomainPort> {
    Arc::new(UnavailableApplicationDomains)
}

#[cfg(test)]
mod tests {
    use super::DomainCommand;

    #[test]
    fn domain_command_names_are_unique() {
        let mut names = DomainCommand::ALL
            .iter()
            .map(|command| command.as_str())
            .collect::<Vec<_>>();
        names.sort_unstable();
        let before = names.len();
        names.dedup();
        assert_eq!(names.len(), before);
    }

    #[test]
    fn capability_scopes_include_registered_domain_scopes() {
        let scopes = DomainCommand::capability_scopes();
        for command in DomainCommand::ALL {
            assert!(
                scopes.contains(&command.required_scope()),
                "{} scope {} missing from capabilities",
                command.as_str(),
                command.required_scope()
            );
        }
        assert!(!scopes.contains(&"workspace.write"));
        assert!(!scopes.contains(&"desktop.tauri"));
    }
}

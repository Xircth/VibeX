export function receiptStatusCopy(
  receipt: DeliveryReceipt | null | undefined,
  labels: {
    queued?: string;
    claimed?: string;
    failed?: string;
    passed?: string;
    timedOut?: string;
    cancelled?: string;
    replied?: string;
  } = {}
): string {
  const state = String(receipt?.state ?? '');
  if (state === 'passed') return labels.passed ?? COPY.receiptPassed;
  if (state === 'timed_out') return labels.timedOut ?? COPY.receiptTimedOut;
  if (state === 'cancelled') return labels.cancelled ?? COPY.receiptCancelled;
  if (state === 'replied') return labels.replied ?? COPY.receiptReplied;
  const delivered = String(receipt?.delivered ?? '');
  const hasError =
    state === 'failed' ||
    delivered === 'failed' ||
    (typeof receipt?.error_code === 'string' &&
      Boolean(receipt.error_code) &&
      state !== 'cancelled' &&
      state !== 'timed_out' &&
      state !== 'passed');
  if (hasError) return labels.failed ?? COPY.receiptFailed;
  if (
    delivered === 'dispatched' ||
    delivered === 'claimed' ||
    delivered === 'started' ||
    state === 'processing'
  ) {
    return labels.claimed ?? COPY.receiptClaimed;
  }
  return labels.queued ?? COPY.receiptQueued;
}

export function resolveMessageReceipts(
  envelope: SpaceEnvelopeParties | null | undefined,
  explicitReceipts: ReadonlyArray<DeliveryReceipt> | null | undefined
): DeliveryReceipt[] {
  if (Array.isArray(explicitReceipts) && explicitReceipts.length > 0) {
    return [...explicitReceipts];
  }
  const derived: DeliveryReceipt[] = [];
  const seen = new Set<string>();
  for (const name of envelopeRecipientNames(envelope)) {
    if (isHumanPersonLabel(name) || isSystemPartyName(name) || seen.has(name)) {
      continue;
    }
    seen.add(name);
    derived.push({
      nickname: name,
      delivered: 'claimed',
    });
  }
  return derived;
}


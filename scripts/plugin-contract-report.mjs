#!/usr/bin/env node
// Generates docs/plugin-contract/bindings.md from the two binding registries,
// the host-api catalog, the contribution-kind catalog, and the official plugin
// manifests. Exits 0: this is a report, not a gate.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const read = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const hostApi = read('packages/plugin-contract/catalog/host-api.v1.json');
const hostBindings = read('packages/plugin-contract/catalog/host-bindings.v1.json');
const kinds = read('packages/plugin-contract/catalog/contribution-kinds.v1.json');
const contributionBindings = read('packages/plugin-contract/catalog/contribution-bindings.v1.json');

const apiOps = new Set(hostApi.operations.map((op) => op.id));
const entries = hostBindings.entries;
const opEntries = entries.filter((entry) => entry.kind === 'op');
const capabilityEntries = entries.filter((entry) => entry.kind === 'capability');
const reachedOps = opEntries.filter((entry) => apiOps.has(entry.name) && entry.reaches_core);
const undeclared = entries.filter((entry) => entry.status === 'undeclared');
const implFile = (implementation) => implementation.split(':')[0];
const fileExists = (rel) => fs.existsSync(path.join(ROOT, rel));
const missingImpl = [...new Set(entries.map((e) => implFile(e.implementation)))].filter(
  (file) => !fileExists(file),
);
function sqlxCount(file) {
  const full = path.join(ROOT, file);
  if (!fs.existsSync(full)) return 0;
  return (fs.readFileSync(full, 'utf8').match(/sqlx::/g) ?? []).length;
}
const implFiles = [...new Set(entries.map((e) => implFile(e.implementation)))].filter(fileExists);
const sqlxFiles = implFiles
  .map((file) => ({ file, count: sqlxCount(file) }))
  .filter((item) => item.count > 0);

// Official plugins: one directory per plugin, manifest at .vibex-plugin/plugin.json
const officialPlugins = [];
const pluginKinds = new Map();
const hostCallUsage = new Map();
for (const dir of fs.readdirSync(path.join(ROOT, 'plugins'))) {
  const manifestPath = path.join('plugins', dir, '.vibex-plugin', 'plugin.json');
  if (!fs.existsSync(path.join(ROOT, manifestPath))) continue;
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, manifestPath), 'utf8'));
  officialPlugins.push({ dir, id: manifest.id, manifestPath: manifestPath.split(path.sep).join('/') });
  for (const integration of manifest.integrations ?? []) {
    const list = pluginKinds.get(integration.kind) ?? [];
    list.push(manifest.id);
    pluginKinds.set(integration.kind, list);
  }
  for (const rel of walk(path.join(ROOT, 'plugins', dir))) {
    if (!/\.(mjs|ts)$/.test(rel) || /(^|[\\/])(test|tests)([\\/]|$)|\.test\./.test(rel)) continue;
    for (const match of fs
      .readFileSync(rel, 'utf8')
      .matchAll(/host\.call\(\s*['"]([a-z][a-z.\-]*)['"]\s*,\s*['"]([^'"]+)['"]/g)) {
      const [capability, operation] = [match[1], match[2]];
      const usage = hostCallUsage.get(capability) ?? new Map();
      usage.set(operation, [...(usage.get(operation) ?? []), rel.slice(ROOT.length + 1).split(path.sep).join('/')]);
      hostCallUsage.set(capability, usage);
    }
  }
}
function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const catalogKinds = new Set(kinds.kinds.map((kind) => kind.id));
const usedKinds = [...pluginKinds.keys()];
const unregisteredKinds = usedKinds.filter((kind) => !catalogKinds.has(kind));
const unusedKinds = kinds.kinds
  .filter((kind) => !pluginKinds.has(kind.id))
  .map((kind) => ({
    kind: kind.id,
    status: kind.status,
    binding: contributionBindings.entries.find((entry) => entry.kind === kind.id),
  }));
const unknownContributions = contributionBindings.entries.filter(
  (entry) => entry.consumer === 'unknown' || entry.example_plugin === 'unknown',
);
const statusDrift = contributionBindings.entries
  .map((entry) => ({
    kind: entry.kind,
    bindingStatus: entry.status,
    catalogStatus: kinds.kinds.find((kind) => kind.id === entry.kind)?.status,
  }))
  .filter((item) => item.catalogStatus && item.bindingStatus !== item.catalogStatus);

const lines = [];
const push = (...items) => lines.push(...items);
const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

push('# Host and contribution bindings', '');
push('<!-- generated by scripts/plugin-contract-report.mjs; do not edit by hand -->', '');
push('Registry: `catalog/host-bindings.v1.json` (one entry per host-api op plus one per');
push('`host.call` capability) and `catalog/contribution-bindings.v1.json` (one entry per');
push('contribution kind). `reaches_core` means the implementing file references');
push('`application::` at least once, which is the same test `scripts/check-arch-*.mjs`');
push('will apply. `status` is `ready` (registered and implemented), `preview` (registered,');
push('but the implementation is a fallback, a no-op, or partial; for contribution kinds,');
push('the Host consumer exists but no official plugin ships the kind yet), or `undeclared`');
push('(implemented or reachable, but absent from `host-api.v1.json`).');
push('');

push('## Summary', '');
push(`- host-api ops: **${apiOps.size}**`);
const registeredCapabilities = capabilityEntries.filter((entry) =>
  [...apiOps].some((op) => op === entry.name || op.startsWith(`${entry.name}.`)),
);
push(`- host.call capabilities: **${capabilityEntries.length}** (${registeredCapabilities.length} registered in host-api.v1.json, ${capabilityEntries.length - registeredCapabilities.length} absent)`);
push(`- binding entries: ${entries.length} (${opEntries.length} op, ${capabilityEntries.length} capability)`);
push(`- host-api ops with \`reaches_core=true\`: **${reachedOps.length} / ${apiOps.size}**`);
push(`- implementation files containing \`sqlx::\`: **${sqlxFiles.length}**${sqlxFiles.length ? ` (${sqlxFiles.map((item) => `\`${item.file}\` ${item.count}`).join(', ')})` : ''}`);
push(`- contribution kinds: ${kinds.kinds.length} catalogued, ${usedKinds.length} used by official plugins`);
push(`- official plugins scanned: ${officialPlugins.length}`);
push('');

const usedOps = new Set([...hostCallUsage.keys()]);

push('## 1. Unregistered but used', '');
push('| Type | Name | Evidence |');
push('| --- | --- | --- |');
for (const entry of undeclared) {
  const usage = entry.kind === 'capability' ? hostCallUsage.get(entry.name) : null;
  const operations = usage ? [...usage.keys()].join(', ') : '';
  push(`| ${entry.kind} | \`${cell(entry.name)}\` | implemented at \`${cell(implFile(entry.implementation))}\`${operations ? `; plugin operations: ${cell(operations)}` : ''}; ${cell(entry.notes)} |`);
}
for (const kind of unregisteredKinds) {
  const users = pluginKinds.get(kind) ?? [];
  push(`| kind | \`${cell(kind)}\` | declared by ${users.map((id) => `\`${id}\``).join(', ')}; accepted by \`crates/plugins/src/package.rs\` but missing from \`contribution-kinds.v1.json\` |`);
}
if (undeclared.length === 0 && unregisteredKinds.length === 0) push('| — | — | none |');
push('');

push('## 2. Registered but unused', '');
push('| Kind | Status | Binding consumer | Note |');
push('| --- | --- | --- | --- |');
for (const item of unusedKinds) {
  push(`| \`${cell(item.kind)}\` | ${item.status} | \`${cell(item.binding?.consumer ?? 'unknown')}\` | no official plugin declares it |`);
}
if (unusedKinds.length === 0) push('| — | — | — | none |');
push('');
push('Capabilities declared but never called by an official plugin (informational, not a');
push('failure by itself — some are host-side only):');
push('');
const unusedCapabilities = capabilityEntries.filter(
  (entry) => !usedOps.has(entry.name) && !hostCallUsage.has(entry.name),
);
push(unusedCapabilities.length ? unusedCapabilities.map((entry) => `\`${entry.name}\``).join(', ') : 'none');
push('');

push('## 3. Bound to implementations that do not reach the Application Core', '');
push('| Capability / op | Implementation | Port | Ops bound |');
push('| --- | --- | --- | --- |');
const byCapability = new Map();
const familyOf = (entry) => {
  if (entry.kind === 'capability') return entry.name;
  const candidates = capabilityEntries
    .map((capability) => capability.name)
    .filter((name) => entry.name.startsWith(`${name}.`))
    .sort((a, b) => b.length - a.length);
  return candidates[0] ?? entry.name.split('.').slice(0, 2).join('.');
};
for (const entry of entries.filter((item) => !item.reaches_core)) {
  const key = familyOf(entry);
  const group = byCapability.get(key) ?? { files: new Set(), port: new Set(), count: 0 };
  group.files.add(implFile(entry.implementation));
  group.port.add(entry.port_trait);
  group.count += 1;
  byCapability.set(key, group);
}
for (const [key, group] of byCapability) {
  push(`| \`${cell(key)}\` | ${[...group.files].map((file) => `\`${cell(file)}\``).join(', ')} | ${[...group.port].map((port) => `\`${cell(port)}\``).join(', ')} | ${group.count} |`);
}
push('');

push('## Unresolved', '');
push(missingImpl.length ? missingImpl.map((file) => `- implementation file not found: \`${file}\``).join('\n') : '- every registered implementation file exists');
push('');
push(
  unknownContributions.length
    ? unknownContributions.map((entry) => `- \`${entry.kind}\`: consumer or example plugin not traced; see \`contribution-bindings.v1.json\``).join('\n')
    : '- no contribution binding has an unknown consumer or example plugin',
);
push('');
push(
  statusDrift.length
    ? statusDrift.map((item) => `- \`${item.kind}\`: contribution-bindings says \`${item.bindingStatus}\`, contribution-kinds says \`${item.catalogStatus}\``).join('\n')
    : '- contribution-bindings status matches contribution-kinds for every kind',
);
push('');

push('## Appendix: host-api op bindings', '');
push('| Op | Port trait | Port method | Implementation | reaches_core | Status |');
push('| --- | --- | --- | --- | --- | --- |');
for (const entry of opEntries.filter((item) => apiOps.has(item.name))) {
  push(`| \`${cell(entry.name)}\` | \`${cell(entry.port_trait)}\` | \`${cell(entry.port_method)}\` | \`${cell(entry.implementation)}\` | ${entry.reaches_core} | ${entry.status} |`);
}
push('');

fs.mkdirSync(path.join(ROOT, 'docs/plugin-contract'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/plugin-contract/bindings.md'), lines.join('\n'));

console.log(`host-api ops: ${apiOps.size}`);
console.log(`binding entries: ${entries.length} (${opEntries.length} op, ${capabilityEntries.length} capability)`);
console.log(`reaches_core=true among host-api ops: ${reachedOps.length}/${apiOps.size}`);
console.log(`implementation files with sqlx::: ${sqlxFiles.length}${sqlxFiles.length ? ` (${sqlxFiles.map((item) => `${item.file}=${item.count}`).join(', ')})` : ''}`);
console.log(`table 1 (unregistered but used): ${undeclared.length + unregisteredKinds.length}`);
console.log(`table 2 (registered but unused kinds): ${unusedKinds.length}`);
console.log(`table 3 (no core reach): ${entries.filter((entry) => !entry.reaches_core).length} entries across ${byCapability.size} capabilities`);
console.log(`unknown / untraced: ${unknownContributions.length + missingImpl.length}`);
console.log('wrote docs/plugin-contract/bindings.md');
